"""Mobile-performance audit of the published watch GLBs (host-side, numpy only).

    python3 -B -m pipeline.glb_audit [glob] [out.md]     # default models/watches/*.glb, writes docs/3d/GLB_AUDIT.md

Per file: size, glTF nodes/meshes/primitives/materials, vertices, triangles, texture pixel sizes (read from the embedded JPEG/PNG
headers), world-space extent in mm (x, y = front plane, z = depth) and the front-relief depth ratio z / min(x, y). Facts only; the
limits listed in the table header are the working targets for mobile (not pass/fail verdicts on visual quality).
"""
import glob
import itertools
import json
import struct
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
TARGET = {"size_mb": 2.5, "triangles": 60000, "tex_px": 2048}


def load(path):
    b = path.read_bytes()
    jl = struct.unpack("<I4s", b[12:20])[0]
    j = json.loads(b[20:20 + jl])
    off = 20 + jl
    bl = struct.unpack("<I4s", b[off:off + 8])[0]
    return j, b[off + 8:off + 8 + bl], len(b)


def img_size(data):
    if data[:8] == b"\x89PNG\r\n\x1a\n":
        return struct.unpack(">II", data[16:24])
    i = 2
    while i < len(data):  # JPEG: walk the markers to the SOF
        m = data[i + 1]
        n = struct.unpack(">H", data[i + 2:i + 4])[0]
        if m in (0xC0, 0xC1, 0xC2):
            h, w = struct.unpack(">HH", data[i + 5:i + 9])
            return w, h
        i += 2 + n
    return 0, 0


def mat(n):
    if "matrix" in n:
        return np.array(n["matrix"]).reshape(4, 4).T
    x, y, z, w = n.get("rotation", [0, 0, 0, 1])
    R = np.array([[1 - 2 * (y * y + z * z), 2 * (x * y - z * w), 2 * (x * z + y * w)],
                  [2 * (x * y + z * w), 1 - 2 * (x * x + z * z), 2 * (y * z - x * w)],
                  [2 * (x * z - y * w), 2 * (y * z + x * w), 1 - 2 * (x * x + y * y)]])
    M = np.eye(4)
    M[:3, :3] = R * np.array(n.get("scale", [1, 1, 1]))
    M[:3, 3] = n.get("translation", [0, 0, 0])
    return M


def audit(path):
    j, binary, size = load(path)
    nodes = j["nodes"]
    parent = {c: i for i, n in enumerate(nodes) for c in n.get("children", [])}

    def world(i):
        M = mat(nodes[i])
        return world(parent[i]) @ M if i in parent else M

    lo, hi = np.full(3, 1e9), np.full(3, -1e9)
    verts = tris = prims = 0
    for i, n in enumerate(nodes):
        if "mesh" not in n:
            continue
        W = world(i)
        for p in j["meshes"][n["mesh"]]["primitives"]:
            prims += 1
            a = j["accessors"][p["attributes"]["POSITION"]]
            verts += a["count"]
            for c in itertools.product(*[(a["min"][k], a["max"][k]) for k in range(3)]):
                v = (W @ np.array([*c, 1]))[:3]
                lo, hi = np.minimum(lo, v), np.maximum(hi, v)
            tris += j["accessors"][p["indices"]]["count"] // 3 if "indices" in p else a["count"] // 3
    ext = (hi - lo) * 1000
    tex = []
    for im in j.get("images", []):
        bv = j["bufferViews"][im["bufferView"]]
        tex.append(img_size(binary[bv.get("byteOffset", 0):bv.get("byteOffset", 0) + bv["byteLength"]]))
    return {"file": path.name, "mb": size / 1e6, "meshes": len(j["meshes"]), "prims": prims, "mats": len(j.get("materials", [])),
            "verts": verts, "tris": tris, "tex": tex, "ext": ext, "ratio": ext[2] / min(ext[0], ext[1])}


def main():
    pat = sys.argv[1] if len(sys.argv) > 1 else "models/watches/*.glb"
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "docs/3d/GLB_AUDIT.md"
    rows = [audit(Path(p)) for p in sorted(glob.glob(str(ROOT / pat)))]
    lines = ["# GLB audit (watch front reliefs)", "",
             "Generated by `python3 -B -m pipeline.glb_audit`. Facts about each published GLB, for mobile-performance review. Working targets: "
             "file <= %.1f MB, <= %d triangles, texture <= %d px on the long side (guides, not visual-quality verdicts); real-device frame-rate checks "
             "are a separate manual step." % (TARGET["size_mb"], TARGET["triangles"], TARGET["tex_px"]), "",
             "| GLB | MB | meshes | prims | mats | verts | tris | textures (px) | x mm | y mm | z mm | z / min(x,y) | flags |", "|" + " --- |" * 13]
    for r in rows:
        flags = []
        if r["mb"] > TARGET["size_mb"]:
            flags.append("size")
        if r["tris"] > TARGET["triangles"]:
            flags.append("tris")
        if any(max(t) > TARGET["tex_px"] for t in r["tex"]):
            flags.append("tex")
        lines.append("| %s | %.2f | %d | %d | %d | %d | %d | %s | %.1f | %.1f | %.1f | %.2f | %s |" % (
            r["file"], r["mb"], r["meshes"], r["prims"], r["mats"], r["verts"], r["tris"], " + ".join("%dx%d" % t for t in r["tex"]),
            r["ext"][0], r["ext"][1], r["ext"][2], r["ratio"], ", ".join(flags) or "-"))
    out.write_text("\n".join(lines) + "\n")
    print("%d files; over size %d, over tris %d, over tex %d -> %s" % (
        len(rows), sum(r["mb"] > TARGET["size_mb"] for r in rows), sum(r["tris"] > TARGET["triangles"] for r in rows),
        sum(any(max(t) > TARGET["tex_px"] for t in r["tex"]) for r in rows), out))


if __name__ == "__main__":
    main()
